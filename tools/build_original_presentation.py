"""Compile themed art for the remaining stock unique portraits and setup maps."""
from pathlib import Path
import shutil
import subprocess
import tempfile

from PIL import Image, ImageOps

from standardize_icons import ROOT, frame_cell

SIZES = (256,128,80,64,48,45,32,24,16)
RECORDS = (
    ('RoulsAscendancy', "Rouls", 'CIVILIZATION_ROULS_ASCENDANCY', 3, 2,
     ('UNIT_ROULS_HOLLOWHOUND', 'UNIT_ROULS_MATRIARCH', 'UNIT_ROULS_BUDDY',
      'BUILDING_ROULS_SOMATIC_LATTICE', 'BUILDING_ROULS_CHOIR_ETERNAL')),
    ('LunaNetwork', "Luna", 'CIVILIZATION_GPT_LUNA', 2, 2,
     ('UNIT_LUNA_PACKET_SETTLER', 'BUILDING_LUNA_CACHE_NODE')),
)
SQL = 'Shared/SQL/90_OriginalPresentation.sql'
RESAMPLE = Image.Resampling.LANCZOS


def split_sheet(path, columns, rows):
    with Image.open(path) as source:
        image = source.convert('RGBA')
    return [image.crop((image.width*x//columns+3, image.height*y//rows+3,
                        image.width*(x+1)//columns-3, image.height*(y+1)//rows-3))
            for y in range(rows) for x in range(columns)]


def compile_art():
    actions = []
    paths = [SQL]
    for folder, prefix, civilization, columns, rows, objects in RECORDS:
        cells = split_sheet(ROOT / 'art-source' / folder / 'Presentation.png', columns, rows)
        atlas = f'{prefix.upper()}_UNIQUE_OBJECT_ATLAS'
        assets = ROOT / folder / 'Art'
        master = Image.new('RGBA', (256 * len(objects),256))
        for index, cell in enumerate(cells[:len(objects)]):
            master.paste(ImageOps.fit(cell,(256,256),RESAMPLE),(index*256,0))
        master.save(ROOT / 'art-source/IconAtlasMasters' / f'{prefix}UniqueObjects256.png')
        rows_sql = []
        encoded = {}
        for size in SIZES:
            sheet = Image.new('RGBA',(size*len(objects),size))
            for index in range(len(objects)):
                cell = master.crop((index*256,0,(index+1)*256,256))
                sheet.paste(frame_cell(cell,size),(index*size,0))
            name = f'{prefix}UniqueObjects{size}.dds'
            rows_sql.append(f"('{atlas}',{size},'{name}',{len(objects)},1)")
            encoded[name] = sheet
        map_name = f'{prefix}Map.dds'
        encoded[map_name] = ImageOps.fit(cells[len(objects)],(360,412),RESAMPLE)
        converter = shutil.which('texconv') or shutil.which('texconv.exe')
        assert converter, 'DirectXTex texconv is required to encode legacy DXT5'
        (ROOT/'.tools').mkdir(exist_ok=True)
        with tempfile.TemporaryDirectory(dir=ROOT/'.tools') as temporary:
            stage = Path(temporary).resolve()
            assert stage.parent == (ROOT/'.tools').resolve()
            inputs = []
            for name, image in encoded.items():
                if image.width%4 or image.height%4:
                    image.save(assets/name)
                    continue
                path = (stage/name).with_suffix('.png')
                image.save(path)
                inputs.append(str(path))
            subprocess.run([converter,'-nologo','-y','-dx9','-f','DXT5','-m','1',
                            '-o',str(stage),*inputs],check=True,capture_output=True)
            for path in stage.glob('*.dds'):
                (assets/path.name).write_bytes(path.read_bytes())
        paths.extend((assets/name).relative_to(ROOT).as_posix() for name in encoded)
        actions.append('INSERT INTO IconTextureAtlases(Atlas,IconSize,Filename,IconsPerRow,IconsPerColumn) VALUES\n'
                       + ',\n'.join(rows_sql) + ';')
        actions.append(f"UPDATE Civilizations SET MapImage='{map_name}' WHERE Type='{civilization}';")
        for index, unit_or_building in enumerate(objects):
            table = 'Units' if unit_or_building.startswith('UNIT_') else 'Buildings'
            actions.append(f"UPDATE {table} SET IconAtlas='{atlas}',PortraitIndex={index} WHERE Type='{unit_or_building}';")
    (ROOT/SQL).parent.mkdir(exist_ok=True)
    (ROOT/SQL).write_text('-- Generated by tools/build_original_presentation.py. Presentation fields only.\n'
                          + '\n'.join(actions)+'\n',encoding='utf-8',newline='\n')
    return paths


if __name__ == '__main__':
    compile_art()
